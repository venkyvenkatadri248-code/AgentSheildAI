def extract_tool_invocation(agent: Agent, prompt: str) -> Optional[Dict[str, Any]]:
    """
    Analyzes prompt intent against agent capabilities and security boundaries.
    Detects when a user asks the agent to perform an action or attempts an unauthorized cross-tool action.
    """
    p = prompt.strip()
    p_lower = p.lower()

    # 1. Check for email actions (Mail Agent tools or cross-boundary attempts)
    email_match = re.search(r'[\w\.-]+@[\w\.-]+\.\w+', p)
    if any(k in p_lower for k in ["send email", "send an email", "send mail", "dispatch email", "deliver email"]):
        recipient = email_match.group(0) if email_match else "recipient@company.internal"
        subject_match = re.search(r'subject[:\s]+(["\']?)(.*?)\1(?:$|\n|with body|body)', p, re.IGNORECASE)
        subject = subject_match.group(2).strip() if subject_match else "Security Platform Notice"
        body = p
        return {
            "tool_name": "send_authorized_email",
            "arguments": {
                "recipient": recipient,
                "subject": subject,
                "body": body
            }
        }

    if any(k in p_lower for k in ["draft email", "draft an email", "compose email", "write email", "prepare email"]):
        recipient = email_match.group(0) if email_match else "recipient@company.internal"
        subject_match = re.search(r'subject[:\s]+(["\']?)(.*?)\1(?:$|\n|with body|body)', p, re.IGNORECASE)
        subject = subject_match.group(2).strip() if subject_match else "Draft Communication"
        return {
            "tool_name": "draft_email",
            "arguments": {
                "recipient": recipient,
                "subject": subject,
                "body": f"Draft prepared by {agent.name} for: {p}"
            }
        }

    if any(k in p_lower for k in ["search mailbox", "search inbox", "find email", "check messages", "lookup email", "search mail"]):
        q = re.sub(r'^(please\s+)?(can you\s+)?(search mailbox|search inbox|find email|check messages)\s+(for\s+)?', '', p, flags=re.IGNORECASE).strip()
        return {
            "tool_name": "search_mailbox",
            "arguments": {"query": q or "security"}
        }

    if any(k in p_lower for k in ["summarize email", "summarize thread", "email summary"]):
        return {
            "tool_name": "summarize_email_thread",
            "arguments": {"thread_id": "thread_sec_001"}
        }

    # 2. Check for Document Agent operations
    path_traversal_match = re.search(r'(\.\.[\\\/][^\s]+|[\\\/]etc[\\\/]passwd|[\\\/]windows[\\\/]system32)', p)
    if path_traversal_match:
        return {
            "tool_name": "read_document_content",
            "arguments": {
                "file_id": path_traversal_match.group(0),
                "file_path": path_traversal_match.group(0)
            }
        }

    if any(k in p_lower for k in ["create document", "write file", "save document", "new document", "create file", "write document"]):
        name_match = re.search(r'(?:called|named|file|document)\s+([a-zA-Z0-9_\-\.]+)', p, re.IGNORECASE)
        filename = name_match.group(1) if name_match else "report_draft.md"
        return {
            "tool_name": "create_document",
            "arguments": {
                "filename": filename,
                "content": f"# Document Generated by {agent.name}\n\nUser request: {p}\n\nSecurity status: Verified in sandbox."
            }
        }

    if any(k in p_lower for k in ["edit document", "update document", "modify file", "update file", "edit file"]):
        file_match = re.search(r'(?:file|document)\s+([a-zA-Z0-9_\-\.]+)', p, re.IGNORECASE)
        file_arg = file_match.group(1) if file_match else "file_sample"
        return {
            "tool_name": "edit_document",
            "arguments": {
                "file_id": file_arg,
                "new_content": f"# Updated Content\n\nModifications applied at {datetime.utcnow().isoformat()}"
            }
        }

    if any(k in p_lower for k in ["summarize document", "summarize file", "summary of document", "summarize report"]):
        file_match = re.search(r'(?:file|document)\s+([a-zA-Z0-9_\-\.]+)', p, re.IGNORECASE)
        file_arg = file_match.group(1) if file_match else "file_sample"
        return {
            "tool_name": "summarize_document",
            "arguments": {"file_id": file_arg}
        }

    if any(k in p_lower for k in ["list file", "list files", "show file", "show files", "my files", "all files", "uploaded files", "view files"]):
        return {
            "tool_name": "list_user_files",
            "arguments": {}
        }

    if any(k in p_lower for k in ["read file", "read document", "cat ", "view file", "show document", "open file"]):
        file_arg = "file_document_sample"
        file_match = re.search(r'(?:file|document|id|read|cat)\s+([a-zA-Z0-9_\-\./\\]+)', p, re.IGNORECASE)
        if file_match and file_match.group(1).lower() not in ["content", "data", "it", "this"]:
            file_arg = file_match.group(1)
        return {
            "tool_name": "read_document_content",
            "arguments": {"file_id": file_arg}
        }

    # 3. Check for Data Analysis operations
    if any(k in p_lower for k in ["data quality", "cleanliness", "missing values", "duplicate check", "validate dataset", "quality audit"]):
        file_arg = "dataset_sample"
        file_match = re.search(r'(?:dataset|file|table)\s+([a-zA-Z0-9_\-\.]+)', p, re.IGNORECASE)
        if file_match:
            file_arg = file_match.group(1)
        return {
            "tool_name": "validate_dataset_quality",
            "arguments": {"file_id": file_arg}
        }

    if any(k in p_lower for k in ["summary report", "data report", "dataset report", "full analysis", "comprehensive report"]):
        file_arg = "dataset_sample"
        file_match = re.search(r'(?:dataset|file|table)\s+([a-zA-Z0-9_\-\.]+)', p, re.IGNORECASE)
        if file_match:
            file_arg = file_match.group(1)
        return {
            "tool_name": "generate_data_summary_report",
            "arguments": {"file_id": file_arg}
        }

    if any(k in p_lower for k in ["schema", "columns", "data types", "dtypes", "inspect dataset"]):
        file_arg = "dataset_sample"
        file_match = re.search(r'(?:dataset|file|table)\s+([a-zA-Z0-9_\-\.]+)', p, re.IGNORECASE)
        if file_match:
            file_arg = file_match.group(1)
        return {
            "tool_name": "inspect_dataset_schema",
            "arguments": {"file_id": file_arg}
        }

    if any(k in p_lower for k in ["stats", "statistics", "descriptive stats", "mean", "median", "summary stats", "distribution", "variance"]):
        file_arg = "dataset_sample"
        file_match = re.search(r'(?:dataset|file|table)\s+([a-zA-Z0-9_\-\.]+)', p, re.IGNORECASE)
        if file_match:
            file_arg = file_match.group(1)
        return {
            "tool_name": "calculate_descriptive_stats",
            "arguments": {"file_id": file_arg}
        }

    # 4. Check for Research Agent operations (Papers, Web Content, Search)
    if any(k in p_lower for k in ["research paper", "papers on", "arxiv", "scientific paper", "literature review", "scholarly"]):
        topic = re.sub(r'^(please\s+)?(can you\s+)?(find\s+|search\s+)?(research\s+papers\s+on|papers\s+on|arxiv\s+on|scholarly\s+sources\s+on)?', '', p, flags=re.IGNORECASE).strip()
        return {
            "tool_name": "search_research_papers",
            "arguments": {"topic": topic or p}
        }

    url_match = re.search(r'https?://[^\s]+', p)
    if url_match:
        return {
            "tool_name": "extract_web_content",
            "arguments": {"url": url_match.group(0)}
        }

    search_keywords = [
        "search the web", "search web", "web search", "search online", "search for ",
        "look up ", "find sources on", "google ", "browse web for", "research online"
    ]
    is_search = (
        any(k in p_lower for k in search_keywords) or
        p_lower.startswith(("search ", "find info on ", "look up ", "investigate cve"))
    )
    if is_search:
        query = re.sub(r'^(please\s+)?(can you\s+)?(search|look up|find info on|investigate|web search)\s+(for\s+|about\s+|online\s+)?', '', p, flags=re.IGNORECASE).strip()
        if not query:
            query = p
        return {
            "tool_name": "search_web_sources",
            "arguments": {"query": query}
        }

    return None


def format_tool_result_markdown(agent: Agent, tool_name: str, arguments: Dict[str, Any], result: Dict[str, Any]) -> str:
    """Format executed tool output cleanly into markdown with citations, uncertainties, and verification metadata."""
    if tool_name == "search_web_sources":
        sources = result.get("sources", [])
        output = [
            f"### 🌐 Research Findings for: *\"{result.get('query', '')}\"*\n",
            f"Verified knowledge retrieval completed across **{len(sources)}** approved sources:\n"
        ]
        for idx, src in enumerate(sources, 1):
            output.append(f"{idx}. **[{src.get('title')}]({src.get('url')})** ({src.get('author')}, {src.get('year')})")
            output.append(f"   > {src.get('snippet')}\n")
        output.append(f"🔍 **Uncertainty & Limitations:** {result.get('uncertainty_identified', 'None identified.')}")
        output.append(f"ℹ️ **Missing Information Note:** {result.get('missing_information', 'Comprehensive data retrieved.')}")
        return "\n".join(output)

    if tool_name == "search_research_papers":
        papers = result.get("papers", [])
        output = [
            f"### 📚 Academic Literature Search: *\"{result.get('topic', '')}\"*\n",
            f"Retrieved **{len(papers)}** peer-reviewed research papers:\n"
        ]
        for idx, p_item in enumerate(papers, 1):
            authors_str = ", ".join(p_item.get("authors", []))
            output.append(f"{idx}. **{p_item.get('title')}**")
            output.append(f"   - *Authors:* {authors_str} | *Venue:* {p_item.get('venue')}")
            output.append(f"   - *DOI:* `{p_item.get('doi')}` | *Citations:* {p_item.get('citations')}")
            output.append(f"   > {p_item.get('abstract')}\n")
        output.append(f"⚠️ **Identified Uncertainty:** {result.get('uncertainty_identified', '')}")
        return "\n".join(output)

    if tool_name == "list_user_files":
        files = result.get("files", [])
        if not files:
            return "📁 **Uploaded Documents:**\n\nYou currently have no files in your workspace sandbox. Upload documents for analysis using the attachment button."
        output = [
            f"📁 **User Uploaded Documents ({len(files)} files found):**\n",
            "| Filename | Type | Size | Uploaded |",
            "| :--- | :--- | :--- | :--- |"
        ]
        for f in files:
            size_kb = round(f.get("size_bytes", 0) / 1024, 1)
            output.append(f"| `{f.get('filename')}` | {f.get('file_type')} | {size_kb} KB | {f.get('created_at', '')[:10]} |")
        return "\n".join(output)

    if tool_name == "read_document_content":
        content = result.get("content", "")
        return f"📄 **Document Content (`{result.get('filename', arguments.get('file_id'))}`):**\n\n```\n{content}\n```"

    if tool_name == "create_document":
        return (
            f"📝 **Document Created & Verified:**\n\n"
            f"- **Filename:** `{result.get('filename')}`\n"
            f"- **Storage Path:** `{result.get('storage_path')}`\n"
            f"- **Size:** `{result.get('size_bytes')} bytes`\n"
            f"- **SHA-256 Digest:** `{result.get('sha256')}`\n"
            f"- **Verification Status:** `{result.get('verification_status')}`\n\n"
            f"*{result.get('message')}*"
        )

    if tool_name == "edit_document":
        return (
            f"✏️ **Document Modified & Verified:**\n\n"
            f"- **File ID / Name:** `{result.get('filename', arguments.get('file_id'))}`\n"
            f"- **New Size:** `{result.get('size_bytes')} bytes`\n"
            f"- **Verification Status:** `{result.get('verification_status')}`\n\n"
            f"*{result.get('message')}*"
        )

    if tool_name == "summarize_document":
        key_pts = result.get("key_points", [])
        output = [
            f"📋 **Document Summary (`{result.get('filename')}`):**\n",
            f"> {result.get('summary')}\n",
            f"**Key Findings:**"
        ]
        for pt in key_pts:
            output.append(f"- {pt}")
        output.append(f"\n*Verification Status:* `{result.get('verification_status')}`")
        return "\n".join(output)

    if tool_name == "inspect_dataset_schema":
        cols = result.get("columns", [])
        dtypes = result.get("column_types", {})
        rows = result.get("rows", 0)
        output = [
            f"📊 **Dataset Schema Analysis (`{result.get('dataset_name', arguments.get('file_id'))}`):**\n",
            f"- **Total Records:** `{rows}` rows",
            f"- **Total Attributes:** `{len(cols)}` columns\n",
            "| Column Name | Inferred Data Type | Missing Values |",
            "| :--- | :--- | :--- |"
        ]
        missing = result.get("missing_values", {})
        for col in cols:
            output.append(f"| `{col}` | `{dtypes.get(col, 'object')}` | `{missing.get(col, 0)}` |")
        return "\n".join(output)

    if tool_name == "calculate_descriptive_stats":
        stats = result.get("statistics", {})
        return f"📈 **Descriptive Statistics:**\n\n```json\n{json.dumps(stats, indent=2)}\n```\n*Verification:* `{result.get('verification_status')}`"

    if tool_name == "validate_dataset_quality":
        limits = result.get("limitations_identified", [])
        output = [
            f"🧪 **Dataset Quality Audit (`{result.get('dataset_name')}`):**\n",
            f"- **Data Hygiene Score:** `{result.get('data_hygiene_score')}/100`",
            f"- **Total Records:** `{result.get('total_records')}`",
            f"- **Missing Cells:** `{result.get('missing_cells_total')}`",
            f"- **Duplicate Rows:** `{result.get('duplicate_records_total')}`\n",
            f"**Identified Data Limitations:**"
        ]
        for lim in limits:
            output.append(f"- {lim}")
        output.append(f"\n*Verification:* `{result.get('verification_status')}`")
        return "\n".join(output)

    if tool_name == "generate_data_summary_report":
        return (
            f"📑 **Comprehensive Dataset Summary Report (`{result.get('dataset_name')}`):**\n\n"
            f"- **Total Records:** `{result.get('total_rows')}`\n"
            f"- **Attributes:** `{result.get('total_columns')}`\n"
            f"- **Data Hygiene Score:** `{result.get('data_hygiene_score')}/100`\n"
            f"- **Limitations:** {', '.join(result.get('limitations_and_uncertainties', []))}\n"
            f"- **Verification:** `{result.get('verification_status')}`"
        )

    if tool_name == "draft_email":
        return (
            f"✉️ **Email Draft Prepared:**\n\n"
            f"- **Recipient:** `{result.get('recipient')}`\n"
            f"- **Subject:** `{result.get('subject')}`\n\n"
            f"**Message Body:**\n"
            f"> {result.get('body')}\n\n"
            f"*{result.get('notice')}*"
        )

    if tool_name == "search_mailbox":
        msgs = result.get("messages", [])
        output = [
            f"📬 **Mailbox Search Results (Mailbox: `{result.get('mailbox')}` | Query: \"{result.get('query')}\")**\n",
            f"Found **{len(msgs)}** permitted message(s):\n"
        ]
        for m in msgs:
            output.append(f"- **{m.get('subject')}** (From: `{m.get('sender')}` | `{m.get('timestamp')[:10]}`)")
            output.append(f"  > {m.get('snippet')}\n")
        return "\n".join(output)

    if tool_name == "summarize_email_thread":
        actions = result.get("key_action_items", [])
        output = [
            f"📧 **Email Thread Summary (`{result.get('thread_id')}`):**\n",
            f"> {result.get('summary')}\n",
            f"**Action Items:**"
        ]
        for act in actions:
            output.append(f"- {act}")
        return "\n".join(output)

    if tool_name == "send_authorized_email":
        return (
            f"✅ **Email Dispatched Successfully:**\n\n"
            f"- **Recipient:** `{result.get('recipient')}`\n"
            f"- **Subject:** `{result.get('subject')}`\n"
            f"- **Dispatch Confirmation ID:** `{result.get('confirmation_id')}`\n"
            f"- **Gateway Route:** `{result.get('provider')}`\n"
            f"- **Delivery Verification:** `CONFIRMED`"
        )

    return f"**Tool Execution Output (`{tool_name}`):**\n\n```json\n{json.dumps(result, indent=2)}\n```"


class GeminiService:
    @classmethod
    def is_configured(cls) -> bool:
        return bool(settings.GEMINI_API_KEY and settings.GEMINI_API_KEY.strip())

    @classmethod
    def get_status(cls) -> Dict[str, Any]:
        configured = cls.is_configured()
        return {
            "configured": configured,
            "model": settings.GEMINI_MODEL,
            "status": "ready" if configured else "missing_api_key",
            "message": "Connected to Google Gen AI" if configured else "GEMINI_API_KEY environment variable is not configured."
        }

    @classmethod
    async def stream_chat_response(
        cls,
        db: Session,
        actor: User,
        conversation: Conversation,
        agent: Agent,
        user_message_content: str,
    ) -> AsyncGenerator[Dict[str, Any], None]:
        """
        Stream assistant response chunk-by-chunk.
        Enforces Central Security Gateway before any tool action is triggered.
        Directly links agent actions to Dashboard telemetry, alerts, and tool calls.
        """
        yield {
            "event": "start",
            "data": {
                "conversation_id": conversation.id,
                "agent_name": agent.name,
                "model": settings.GEMINI_MODEL if cls.is_configured() else "security_gateway"
            }
        }

        # -------------------------------------------------------------
        # STEP 1: Direct Prompt Injection Check on Raw Input
        # -------------------------------------------------------------
        det = detect_direct_prompt_injection(user_message_content)
        if det.detected:
            decision = CentralSecurityGateway._block_action(
                db=db,
                actor=actor,
                agent=agent,
                decision_id=str(uuid.uuid4()),
                tool_name="chat_input",
                risk_category="prompt_injection",
                severity=det.severity,
                policy=None,
                explanation=f"Direct prompt injection detected in input prompt. {det.reason}.",
                evidence=det.evidence,
                conversation_id=conversation.id
            )

            # Record blocked tool call for dashboard metrics
            tool_call = ToolCall(
                conversation_id=conversation.id,
                agent_id=agent.id,
                tool_name="chat_input",
                arguments={"prompt": user_message_content[:200]},
                result=None,
                security_decision_id=decision.decision_id,
                status="BLOCKED",
                error_message=decision.explanation,
                executed_at=datetime.utcnow()
            )
            db.add(tool_call)
            db.commit()

            notice_text = (
                "I apologize, but I cannot fulfill this request because it violates safety and security policies. "
                "Please let me know if there is another task I can help you with."
            )

            yield {"event": "security_block", "data": decision.dict()}
            yield {"event": "chunk", "data": {"text": notice_text}}
            yield {"event": "done", "data": {"status": "BLOCKED", "tokens": 0}}
            return

        # -------------------------------------------------------------
        # STEP 2: Agent Action & Tool Gate Evaluation
        # -------------------------------------------------------------
        tool_invocation = extract_tool_invocation(agent, user_message_content)

        if tool_invocation:
            tool_name = tool_invocation["tool_name"]
            tool_args = tool_invocation["arguments"]

            # Intercept and inspect with Central Security Gateway
            decision = CentralSecurityGateway.evaluate_tool_call(
                db=db,
                actor=actor,
                agent=agent,
                tool_name=tool_name,
                arguments=tool_args,
                conversation_id=conversation.id
            )

            # Case A: BLOCKED by Security Gateway
            if not decision.allowed and not decision.requires_approval:
                tool_call = ToolCall(
                    conversation_id=conversation.id,
                    agent_id=agent.id,
                    tool_name=tool_name,
                    arguments=tool_args,
                    result=None,
                    security_decision_id=decision.decision_id,
                    status="BLOCKED",
                    error_message=decision.explanation,
                    executed_at=datetime.utcnow()
                )
                db.add(tool_call)
                db.commit()

                # Natural, professional refusal without application technical plumbing
                if decision.risk_category == "unauthorized_tool_invocation":
                    block_text = f"I'm sorry, but as {agent.name}, I am not authorized to perform that action. Please let me know how I can assist you with tasks in my role!"
                elif decision.risk_category == "cross_user_access":
                    block_text = "I cannot access that document or dataset because you do not have permission to view it."
                elif decision.risk_category == "unauthorized_file_modification":
                    block_text = "I cannot modify or access protected configuration files. Please specify an authorized file in your workspace."
                elif decision.risk_category == "dangerous_file_operation":
                    block_text = "I cannot access or process that file format or path. Please select an authorized text or data file."
                elif decision.risk_category == "sensitive_data_exposure":
                    block_text = "I cannot proceed with this request because it contains sensitive confidential information (such as credentials, API keys, or private financial details)."
                elif decision.risk_category == "prohibited_code_execution":
                    block_text = "Executing arbitrary scripts or commands is not permitted. I can help compute standard descriptive statistics and evaluate dataset summaries."
                elif decision.risk_category == "unapproved_database_modification":
                    block_text = "Direct database modifications or destructive SQL commands are not allowed."
                elif decision.risk_category == "unauthorized_network_access":
                    block_text = "I cannot access that network address or internal destination. I can only retrieve information from authorized public web and research sources."
                else:
                    block_text = f"I am unable to complete this request: {decision.explanation}"

                yield {"event": "security_block", "data": decision.dict()}
                yield {"event": "chunk", "data": {"text": block_text}}
                yield {"event": "done", "data": {"status": "BLOCKED", "tokens": 0}}
                return

            # Case B: Human-In-The-Loop Approval Required
            if decision.requires_approval:
                tool_call = ToolCall(
                    conversation_id=conversation.id,
                    agent_id=agent.id,
                    tool_name=tool_name,
                    arguments=tool_args,
                    result=None,
                    security_decision_id=decision.decision_id,
                    status="PENDING_APPROVAL",
                    error_message=decision.explanation,
                    executed_at=datetime.utcnow()
                )
                db.add(tool_call)
                db.commit()

                recipient = tool_args.get("recipient", "recipient")
                subject = tool_args.get("subject", "No Subject")
                body = tool_args.get("body", "")

                approval_text = (
                    f"✉️ **Email Draft Prepared & Waiting for Approval:**\n\n"
                    f"I have composed this message for you:\n\n"
                    f"- **To:** `{recipient}`\n"
                    f"- **Subject:** {subject}\n\n"
                    f"**Message Body:**\n> {body}\n\n"
                    f"*Because this will be sent externally, please confirm or approve before it is dispatched.*"
                )
                yield {"event": "approval_pending", "data": decision.dict()}
                yield {"event": "chunk", "data": {"text": approval_text}}
                yield {"event": "done", "data": {"status": "PENDING_APPROVAL", "tokens": 0}}
                return

            # Case C: ALLOWED -> Execute Tool Safely without technical debug headers

            # Record ToolCall in DB
            tool_call = ToolCall(
                conversation_id=conversation.id,
                agent_id=agent.id,
                tool_name=tool_name,
                arguments=tool_args,
                security_decision_id=decision.decision_id,
                status="ALLOWED",
                executed_at=datetime.utcnow()
            )
            db.add(tool_call)
            db.commit()

            try:
                tool_result = execute_tool(tool_name, tool_args, db=db, actor=actor)
                tool_call.result = tool_result
                tool_call.status = "EXECUTED"
                db.commit()
            except Exception as e:
                logger.error(f"Error executing tool {tool_name}: {e}")
                tool_call.status = "FAILED"
                tool_call.error_message = str(e)
                db.commit()
                tool_result = {"status": "error", "message": str(e)}

            formatted_markdown = format_tool_result_markdown(agent, tool_name, tool_args, tool_result)

            # Stream the formatted tool output to user
            for chunk_part in [formatted_markdown[i:i+120] for i in range(0, len(formatted_markdown), 120)]:
                yield {"event": "chunk", "data": {"text": chunk_part}}
                await asyncio.sleep(0.02)

            yield {
                "event": "done",
                "data": {
                    "status": "COMPLETED",
                    "tokens": len(formatted_markdown.split()),
                    "full_content": formatted_markdown
                }
            }
